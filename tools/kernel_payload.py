"""Build the freestanding ARM64 kernel errata payload."""
from pathlib import Path
import shutil
import subprocess
import struct
import tempfile

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "LiuqinPkg/Library/KernelErrataPatcherLib"
HEADER = ROOT / "Build/Include/KernelPatchPayload.generated.h"


def tool(name):
    """Resolve an external tool, including names with dots such as ld.lld.

    CreateProcess() only appends .exe when the name has no extension, so a
    bare "ld.lld" fails on Windows even though it is on PATH.
    """
    path = shutil.which(name)
    if path is None:
        raise FileNotFoundError(f"{name} was not found on PATH")
    return path


def build(directory):
    directory = Path(directory)
    flags = ["--target=aarch64-none-elf", "-Os", "-ffreestanding", "-fpie",
             "-fvisibility=hidden", "-mcmodel=tiny", "-ffixed-x18", "-mgeneral-regs-only",
             "-fno-stack-protector", "-fno-builtin", "-fno-jump-tables",
             "-fno-asynchronous-unwind-tables", "-fno-unwind-tables",
             "-Wall", "-Wextra", "-Werror"]
    objects = []
    for suffix in ("S", "c"):
        obj = directory / ("payload-" + suffix + ".o")
        subprocess.run(["clang", *flags, "-c", str(SOURCE / ("KernelPatchPayload." + suffix)),
                        "-o", str(obj)], check=True)
        objects.append(str(obj))
    linker = directory / "payload.ld"
    linker.write_text("ENTRY(KepPayloadStart)\nSECTIONS { . = 0; .text : { "
                      "*(.text.entry) *(.text) *(.text.thunk) "
                      "*(.rodata .rodata.*) *(.text.tail) "
                      "} .forbidden : { *(.got*) *(.data*) *(.bss*) } "
                      "ASSERT(SIZEOF(.forbidden) == 0, \"Payload has absolute data/GOT\") "
                      "/DISCARD/ : { *(.comment) *(.note*) *(.eh_frame*) } }\n")
    elf = directory / "payload.elf"
    binary = directory / "payload.bin"
    subprocess.run([tool("ld.lld"), "--no-undefined", "-T", str(linker), *objects,
                    "-o", str(elf)], check=True)
    subprocess.run(["llvm-objcopy", "-O", "binary", "--only-section=.text",
                    str(elf), str(binary)], check=True)
    # Any allocated orphan section would be absent from the exported blob.
    # Reject it, including unexpected GOT/data introduced by a future compiler.
    elf_data = elf.read_bytes()
    section_offset = struct.unpack_from("<Q", elf_data, 40)[0]
    section_stride, section_count = struct.unpack_from("<HH", elf_data, 58)
    for index in range(section_count):
        kind, flags, address, offset, size = struct.unpack_from(
            "<IQQQQ", elf_data, section_offset + index * section_stride + 4)
        if size and flags & 2:
            assert address == 0 and size == binary.stat().st_size and flags == 6, "Unexpected allocated payload section"
        assert not (size and kind in (4, 9)), "Payload retains relocations"
    symbols = {}
    for line in subprocess.check_output(["llvm-nm", "--defined-only", str(elf)], text=True).splitlines():
        fields = line.split()
        if len(fields) == 3:
            symbols[fields[2]] = int(fields[0], 16)
    data = binary.read_bytes()
    assert symbols["KepPayloadStart"] == 0
    assert symbols["KepPayloadTail"] == len(data) - 4
    # The injector uses 16-byte-aligned padding, not a page-aligned ELF load.
    # ADRP's linked low-12 address assumptions would break this relocation.
    for offset in range(0, len(data), 4):
        word = int.from_bytes(data[offset:offset+4], "little")
        assert word & 0x9f000000 != 0x90000000, f"ADRP at {offset:#x} is not byte-position-independent"
    assert len(data) <= 3584, f"Payload {len(data)} exceeds real WinPE PAGELK padding"
    return data, symbols

def render(data, symbols):
    lines = ["/* Generated by tools/kernel_payload.py; do not edit. */",
             "/* SPDX-License-Identifier: BSD-2-Clause-Patent */",
             "#ifndef LIUQIN_KERNEL_PATCH_PAYLOAD_GENERATED_H",
             "#define LIUQIN_KERNEL_PATCH_PAYLOAD_GENERATED_H",
             f"#define LIUQIN_KEP_PAYLOAD_TAIL_OFFSET {symbols['KepPayloadTail']}U",
             "STATIC CONST UINT8 mLiuqinKepPayload[] = {"]
    lines += ["  " + ", ".join(f"0x{x:02X}" for x in data[i:i+12]) + ","
              for i in range(0, len(data), 12)]
    return "\n".join([*lines, "};", "#endif", ""])

if __name__ == "__main__":
    with tempfile.TemporaryDirectory(prefix="liuqin-payload-") as directory:
        data, symbols = build(directory)
        HEADER.write_text(render(data, symbols))
